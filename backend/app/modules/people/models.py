"""People (schema `people`): the reusable person record, base of the future padrón.
See docs/reference/data-model.md §3, D-30..D-32. Sensitive fields are encrypted at the
application level (AES-256-GCM envelope) with HMAC blind indexes for uniqueness and exact
lookups."""

import uuid
from datetime import date, datetime
from typing import Any, ClassVar

from sqlalchemy import (
    CheckConstraint,
    Column,
    Computed,
    Date,
    DateTime,
    Index,
    LargeBinary,
    SmallInteger,
    Text,
    func,
    literal_column,
    text,
)
from sqlmodel import Field

from app.core.db.base import BusinessTable

SCHEMA = "people"
TZ = DateTime(timezone=True)


def _person_fk() -> Any:
    return Field(foreign_key=f"{SCHEMA}.persons.id", ondelete="CASCADE", index=True)


def _geo_fk(table: str) -> Any:
    return Field(
        default=None, foreign_key=f"geography.{table}.id", ondelete="RESTRICT", nullable=True
    )


class Person(BusinessTable, table=True):
    __tablename__ = "persons"
    __table_args__ = (
        Index(
            "uq_persons_curp_hash",
            "curp_hash",
            unique=True,
            postgresql_where=text("deleted_at IS NULL AND curp_hash IS NOT NULL"),
        ),
        Index(
            "ix_persons_search_name_trgm",
            func.f_unaccent(func.lower(literal_column("search_name"))).label("search"),
            postgresql_using="gin",
            postgresql_ops={"search": "gin_trgm_ops"},
        ),
        CheckConstraint("sex IN ('H', 'M', 'X')", name="sex"),
        {"schema": SCHEMA},
    )
    # The audit log is immutable and ARCO purge must leave no personal data behind, so the
    # identifying attributes are stored as "***" (D-93). CURP and contacts are bytes and
    # already masked.
    __audit_masked__: ClassVar[frozenset[str]] = frozenset(
        {
            "given_names",
            "paternal_surname",
            "maternal_surname",
            "search_name",
            "birth_date",
            "sex",
            "birth_entity",
        }
    )

    given_names: str = Field(max_length=120)
    paternal_surname: str = Field(max_length=80)
    maternal_surname: str | None = Field(default=None, max_length=80)
    # Generated by PostgreSQL from the name parts (immutable expression), used for search.
    search_name: str | None = Field(
        default=None,
        sa_column=Column(
            "search_name",
            Text,
            Computed(
                "given_names || ' ' || paternal_surname || ' ' || coalesce(maternal_surname, '')",
                persisted=True,
            ),
        ),
    )
    birth_date: date | None = Field(default=None, sa_type=Date)
    sex: str | None = Field(default=None, max_length=1)
    birth_entity: str | None = Field(default=None, max_length=2)
    curp_ciphertext: bytes | None = Field(default=None, sa_type=LargeBinary)
    curp_hash: bytes | None = Field(default=None, sa_type=LargeBinary)
    curp_coherence_overridden: bool = Field(
        default=False, sa_column_kwargs={"server_default": text("false")}
    )
    key_version: int | None = Field(default=None, sa_type=SmallInteger)
    purge_after: date | None = Field(default=None, sa_type=Date)


class PersonContact(BusinessTable, table=True):
    __tablename__ = "person_contacts"
    __table_args__ = (
        CheckConstraint("contact_type IN ('mobile', 'landline', 'email')", name="contact_type"),
        Index("ix_person_contacts_value_hash", "value_hash"),
        {"schema": SCHEMA},
    )

    person_id: uuid.UUID = _person_fk()
    contact_type: str = Field(sa_type=Text)
    value_ciphertext: bytes = Field(sa_type=LargeBinary)
    value_hash: bytes = Field(sa_type=LargeBinary)
    is_primary: bool = Field(default=False, sa_column_kwargs={"server_default": text("false")})
    key_version: int = Field(sa_type=SmallInteger)


class PersonAddress(BusinessTable, table=True):
    __tablename__ = "person_addresses"
    __table_args__ = (
        CheckConstraint("address_type IN ('home', 'work', 'other')", name="address_type"),
        Index("ix_person_addresses_section_id", "section_id"),
        {"schema": SCHEMA},
    )
    __audit_masked__: ClassVar[frozenset[str]] = frozenset({"postal_code"})

    person_id: uuid.UUID = _person_fk()
    address_type: str = Field(default="home", sa_type=Text)
    # Street, numbers and references, encrypted as one JSON document (D-31).
    address_ciphertext: bytes | None = Field(default=None, sa_type=LargeBinary)
    postal_code: str | None = Field(default=None, max_length=5)
    state_id: uuid.UUID | None = _geo_fk("states")
    municipality_id: uuid.UUID | None = _geo_fk("municipalities")
    section_id: uuid.UUID | None = _geo_fk("sections")
    locality_id: uuid.UUID | None = _geo_fk("localities")
    neighborhood_id: uuid.UUID | None = _geo_fk("neighborhoods")
    is_primary: bool = Field(default=True, sa_column_kwargs={"server_default": text("true")})
    key_version: int | None = Field(default=None, sa_type=SmallInteger)


CONSENT_CHANNELS = ("panel", "paper", "web", "referral_link", "import", "field_app")


class PrivacyNotice(BusinessTable, table=True):
    """A version of a privacy notice (D-82). `code` tells notices apart (`general`, the Peace
    Movement's `peace_movement`); one version per code is current (`valid_to` null)."""

    __tablename__ = "privacy_notices"
    __table_args__ = (
        Index(
            "uq_privacy_notices_code_version",
            "code",
            "version",
            unique=True,
            postgresql_where=text("deleted_at IS NULL"),
        ),
        Index(
            "uq_privacy_notices_current",
            "code",
            unique=True,
            postgresql_where=text("valid_to IS NULL AND deleted_at IS NULL"),
        ),
        {"schema": SCHEMA},
    )

    code: str = Field(max_length=50)
    version: str = Field(max_length=50)
    title: str = Field(max_length=200)
    body: str = Field(sa_type=Text)
    body_sha256: str = Field(max_length=64)
    is_sample: bool = Field(default=False, sa_column_kwargs={"server_default": text("false")})
    valid_from: datetime = Field(sa_type=TZ)
    valid_to: datetime | None = Field(default=None, sa_type=TZ)


class PrivacyConsent(BusinessTable, table=True):
    """Acceptance of a privacy notice (LFPDPPP). Consents given on a catalogued notice copy its
    code and text hash, so the proof survives the notice row (D-82)."""

    __tablename__ = "privacy_consents"
    __table_args__ = (
        CheckConstraint(
            "channel IN (" + ", ".join(f"'{c}'" for c in CONSENT_CHANNELS) + ")", name="channel"
        ),
        {"schema": SCHEMA},
    )
    __audit_masked__: ClassVar[frozenset[str]] = frozenset()

    person_id: uuid.UUID = _person_fk()
    notice_id: uuid.UUID | None = Field(
        default=None, foreign_key=f"{SCHEMA}.privacy_notices.id", ondelete="RESTRICT"
    )
    notice_code: str = Field(
        default="general", max_length=50, sa_column_kwargs={"server_default": "general"}
    )
    notice_version: str = Field(max_length=50)
    notice_text_sha256: str | None = Field(default=None, max_length=64)
    channel: str = Field(sa_type=Text)
    evidence_uri: str | None = Field(default=None, max_length=500)
    accepted_at: datetime = Field(sa_type=TZ)

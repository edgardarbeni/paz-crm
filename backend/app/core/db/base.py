"""Shared table-model building blocks.

- Explicit constraint/index naming (CLAUDE.md §Convenciones, docs/reference/data-model.md §0).
- UUIDv7 primary keys generated by PostgreSQL 18 (`uuidv7()`, D-05).
- Timestamp and soft-delete mixins. Geography tables use `ImportedMixin` instead of
  soft-delete (D-04); see `docs/adr/`.
"""

import uuid
from datetime import datetime

from sqlalchemy import Boolean, DateTime, MetaData, func, text
from sqlmodel import Field, SQLModel

NAMING_CONVENTION = {
    "pk": "pk_%(table_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s__%(referred_table_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
}

metadata: MetaData = SQLModel.metadata
metadata.naming_convention = NAMING_CONVENTION


class UUIDPrimaryKeyMixin(SQLModel):
    id: uuid.UUID | None = Field(
        default=None,
        primary_key=True,
        sa_column_kwargs={"server_default": text("uuidv7()")},
    )


class TimestampMixin(SQLModel):
    created_at: datetime | None = Field(
        default=None,
        sa_type=DateTime(timezone=True),
        sa_column_kwargs={"server_default": func.now(), "nullable": False},
    )
    updated_at: datetime | None = Field(
        default=None,
        sa_type=DateTime(timezone=True),
        sa_column_kwargs={"server_default": func.now(), "onupdate": func.now(), "nullable": False},
    )


class SoftDeleteMixin(SQLModel):
    deleted_at: datetime | None = Field(
        default=None,
        sa_type=DateTime(timezone=True),
        index=False,
    )


class ImportedMixin(SQLModel):
    """For read-only geography rows that only change through imports (D-04)."""

    import_run_id: uuid.UUID | None = Field(default=None)
    is_active: bool = Field(
        default=True,
        sa_type=Boolean,
        sa_column_kwargs={"server_default": text("true"), "nullable": False},
    )


class BusinessTable(SoftDeleteMixin, TimestampMixin, UUIDPrimaryKeyMixin):
    """Base for business tables: UUIDv7 PK + created_at/updated_at/deleted_at.

    Bases are listed in reverse so columns are emitted as id, created_at, updated_at,
    deleted_at, then the model's own columns."""


def pk(row: UUIDPrimaryKeyMixin) -> uuid.UUID:
    """The primary key of a persisted (flushed) row; `id` is only None before the flush."""
    if row.id is None:
        raise RuntimeError(f"{type(row).__name__} has not been flushed yet")
    return row.id
